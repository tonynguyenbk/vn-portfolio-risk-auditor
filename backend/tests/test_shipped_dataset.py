"""The shipped demonstration dataset and the scripts that freeze it.

The bundled CSVs are real market data fetched once by
``scripts/fetch_market_data.py``. They cannot be regenerated byte-identically,
so what is tested is (a) that the committed files still match the checksums
recorded at retrieval, (b) that they satisfy the same sanity checks the fetch
script enforces, and (c) that those checks actually catch what they claim to.
No network access is needed.
"""

from __future__ import annotations

import json
import shutil
from datetime import date
from pathlib import Path

import numpy as np
import pandas as pd
import pytest

from app.services.data_validation import (
    ValidationReport,
    clean_market_frame,
    validate_portfolio,
)
from app.services.returns import align_on_common_dates, log_returns, pivot_long_prices
from scripts.fetch_market_data import (
    BENCHMARK_TICKER,
    MAX_ABS_LOG_RETURN,
    MAX_GAP_CALENDAR_DAYS,
    PORTFOLIO,
    Bar,
    check_series,
    format_price,
)
from scripts.verify_demo_data import verify
from tests.conftest import FLOAT_TOL

DEMO = Path(__file__).resolve().parents[2] / "frontend" / "public" / "demo"


@pytest.fixture(scope="module")
def market() -> pd.DataFrame:
    return pd.read_csv(DEMO / "market_data.csv", dtype={"date": str})


@pytest.fixture(scope="module")
def portfolio() -> pd.DataFrame:
    return pd.read_csv(DEMO / "portfolio.csv")


@pytest.fixture(scope="module")
def manifest() -> dict:
    return json.loads((DEMO / "manifest.json").read_text(encoding="utf-8"))


class TestChecksums:
    def test_committed_files_match_the_manifest(self) -> None:
        assert verify(DEMO) == []

    def test_a_single_altered_byte_is_detected(self, tmp_path: Path) -> None:
        for name in ("manifest.json", "market_data.csv", "portfolio.csv"):
            shutil.copy(DEMO / name, tmp_path / name)
        path = tmp_path / "portfolio.csv"
        path.write_bytes(path.read_bytes().replace(b"0.25", b"0.26", 1))

        problems = verify(tmp_path)
        assert len(problems) == 1
        assert problems[0].startswith("portfolio.csv")

    def test_a_missing_file_is_detected(self, tmp_path: Path) -> None:
        shutil.copy(DEMO / "manifest.json", tmp_path / "manifest.json")
        assert len(verify(tmp_path)) == 2


class TestManifest:
    def test_records_real_data_and_its_source(self, manifest: dict) -> None:
        assert manifest["isSimulated"] is False
        assert manifest["source"]["provider"] == "Vietcap"
        assert manifest["adjustment"] == "adjusted close as provided by Vietcap"
        assert manifest["retrievalDate"]

    def test_lists_exactly_the_tickers_in_the_file(
        self, manifest: dict, market: pd.DataFrame
    ) -> None:
        assert set(manifest["tickers"]) == set(market["ticker"])
        assert manifest["benchmark"] == BENCHMARK_TICKER

    def test_trading_day_count_matches_the_file(
        self, manifest: dict, market: pd.DataFrame
    ) -> None:
        assert manifest["tradingDays"] == market["date"].nunique()
        assert manifest["firstObservation"] == market["date"].min()
        assert manifest["lastObservation"] == market["date"].max()


class TestShippedData:
    def test_portfolio_matches_the_fetch_script(self, portfolio: pd.DataFrame) -> None:
        expected = [(h.ticker, h.weight, h.sector) for h in PORTFOLIO]
        actual = list(portfolio.itertuples(index=False, name=None))
        assert actual == expected
        assert portfolio["weight"].sum() == pytest.approx(1.0, abs=FLOAT_TOL)

    def test_stays_inside_the_requested_period(self, market: pd.DataFrame) -> None:
        assert market["date"].min() >= "2015-01-01"
        assert market["date"].max() <= "2026-10-29"

    def test_every_series_passes_the_fetch_time_sanity_checks(
        self, market: pd.DataFrame
    ) -> None:
        # Re-run the fetch script's checks on what was committed, so a hand edit
        # to the CSV that slips past the checksum update is still caught.
        for ticker, rows in market.groupby("ticker"):
            bars = [
                Bar(date.fromisoformat(d), float(c), int(v))
                for d, c, v in zip(rows["date"], rows["close"], rows["volume"], strict=True)
            ]
            assert check_series(str(ticker), sorted(bars, key=lambda b: b.day)) == []

    def test_alignment_loses_nothing_and_the_engine_accepts_it(
        self, market: pd.DataFrame, portfolio: pd.DataFrame
    ) -> None:
        cleaned, removed, duplicates = clean_market_frame(market)
        assert (removed, duplicates) == (0, 0)

        report = ValidationReport()
        validate_portfolio(portfolio, set(cleaned["ticker"]), report)
        assert report.can_run

        aligned = align_on_common_dates(pivot_long_prices(cleaned), list(portfolio["ticker"]))
        assert len(aligned) == cleaned["date"].nunique()
        assert bool(np.isfinite(log_returns(aligned).to_numpy()).all())


def _bars(*closes: float, start: date = date(2020, 1, 6)) -> list[Bar]:
    """Consecutive weekdays from ``start``."""
    days = pd.bdate_range(start, periods=len(closes))
    return [Bar(d.date(), c, 1) for d, c in zip(days, closes, strict=True)]


class TestSanityChecks:
    """Each check must fire on the defect it names, and only on that."""

    def test_a_clean_series_passes(self) -> None:
        problems = check_series("X", _bars(100, 101, 99, 100.5))
        # Start/end coverage is measured against the real request window, so a
        # short synthetic series reports exactly those two and nothing else.
        assert len(problems) == 2
        assert all("starts late" in p or "ends early" in p for p in problems)

    def test_a_move_beyond_the_price_limit_is_flagged(self) -> None:
        jump = 100 * float(np.exp(MAX_ABS_LOG_RETURN + 0.001))
        problems = check_series("X", _bars(100, jump))
        assert any("log return" in p for p in problems)

    def test_a_limit_down_day_is_not_flagged(self) -> None:
        # -7% is the HOSE limit; ln(0.93) = -7.26% must pass.
        problems = check_series("X", _bars(100, 93))
        assert not any("log return" in p for p in problems)

    def test_a_non_positive_price_is_flagged(self) -> None:
        problems = check_series("X", _bars(100, 0, 100))
        assert any("non-positive" in p for p in problems)

    def test_a_long_gap_is_flagged(self) -> None:
        bars = [
            Bar(date(2020, 1, 6), 100, 1),
            Bar(date(2020, 1, 6) + pd.Timedelta(days=MAX_GAP_CALENDAR_DAYS + 1), 100, 1),
        ]
        assert any("-day gap" in p for p in check_series("X", bars))

    def test_a_duplicate_date_is_flagged(self) -> None:
        bars = _bars(100, 101)
        assert any("duplicate" in p for p in check_series("X", [*bars, bars[-1]]))


