"""Verify the committed demonstration CSVs against their recorded checksums.

Run from the repository root::

    uv run --directory backend python scripts/verify_demo_data.py

The demonstration dataset is real market data fetched once and frozen
(``scripts/fetch_market_data.py``). Unlike a seeded synthetic series it cannot
be regenerated byte-identically — the upstream provider may revise history at
any time — so reproducibility rests on the committed files themselves. This
script is what makes that a checked claim: every file listed in
``manifest.json`` must hash to the SHA-256 recorded there.

Exits non-zero, naming each mismatch, if any file is missing or altered.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path


def sha256_of(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def verify(directory: Path) -> list[str]:
    """Return one message per problem. Empty means every checksum matched."""
    manifest_path = directory / "manifest.json"
    if not manifest_path.is_file():
        return [f"{manifest_path} does not exist"]

    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    files: dict[str, str] = manifest.get("files") or {}
    if not files:
        return [f"{manifest_path} lists no files to verify"]

    problems: list[str] = []
    for name, expected in sorted(files.items()):
        path = directory / name
        if not path.is_file():
            problems.append(f"{name}: missing")
            continue
        actual = sha256_of(path)
        if actual != expected:
            problems.append(f"{name}: sha256 {actual} != manifest {expected}")
    return problems


def main() -> None:
    default_dir = Path(__file__).resolve().parents[2] / "frontend" / "public" / "demo"

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--directory", type=Path, default=default_dir)
    args = parser.parse_args()

    problems = verify(args.directory)
    if problems:
        print("Demo data does not match manifest.json:", file=sys.stderr)
        for problem in problems:
            print(f"  - {problem}", file=sys.stderr)
        raise SystemExit(1)

    print(f"All files listed in {args.directory / 'manifest.json'} match their checksums.")


if __name__ == "__main__":
    main()
